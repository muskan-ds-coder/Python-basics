# Rules for Naming Variables in Python
# 1. Variable names must start with a letter (a-z, A-Z) or an underscore (_).
# 2. The rest of the variable name can contain letters, digits (0-9), or underscores.
# 3. Variable names are case-sensitive (e.g., myVar and myvar are different variables).
# 4. Variable names cannot be the same as Python keywords (e.g., if, else, while, etc.).
# 5. Variable names should be descriptive and meaningful to improve code readability.   
a = 5
b = "Hello"
print(a)
print(b)

_muskan = "Hello, World!"
print(_muskan)

# Invalid variable names:
# 1. 2muskan = "Hello"  # Cannot start with a number
# 2. my-yadav = "Hello"  # Cannot contain hyphens
# 3. my yadav = "Hello"  # Cannot contain spaces
# 4. if = "Hello"       # Cannot be a Python keyword
# 5. mu@skan = "Hello"   # Cannot contain special characters like @

